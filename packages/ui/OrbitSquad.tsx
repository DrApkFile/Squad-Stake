import { countUp, entranceProgress, ringAngle, ringDirection, ringPeriod, seatAngle } from './motion';
import { formatNim } from './format';
import { vars } from './css';
import { ScreenHeader } from './ScreenHeader';
import type { SquadStatusTone } from './StatusDot';

export interface OrbitMember {
  /** From data, never generated (AGENTS.md "UI purity" 1). */
  id: string;
  /** Inline Nimiq identicon, generated from the address outside this package (the official
   * package is promise-based and its browser build fetches a sprite, so neither can run in a
   * pure render). `null` renders a neutral seat rather than a wrong face. */
  identiconSvg: string | null;
  tone: SquadStatusTone;
  label: string;
}

export interface OrbitSquadProps {
  /** The squad's goal, in the centre. */
  goal: string;
  members: readonly OrbitMember[];
  /** Sum of the backed commitments in luna — PRD §7.4 "Squad total = Σ backed amounts".
   * `null` means no chain read yet and renders as "—" (AGENTS.md "Never fabricate"). */
  backedLuna: number | null;
  /** Mode A target in luna; `null` in Mode B, where there is no shared target. */
  targetLuna: number | null;
  t?: number | undefined;
  /** No rotation and no count-up: the small preview on a list card. */
  still?: boolean | undefined;
  /** What the centre figure is. A squad page reads the chain and says "backed"; a list card
   * only knows our record of commitments and says "committed" (PRD §7.4, §9.3). */
  totalWord?: 'backed' | 'committed' | undefined;
}

/** Ring diameters as a percentage of the square, outermost first, so the whole figure scales
 * down inside a 375 px viewport instead of overflowing it. */
const RING_DIAMETERS = [88, 67, 46, 25] as const;

function ringCountFor(members: number) {
  if (members <= 4) return 2;
  if (members <= 8) return 3;
  return 4;
}

/** Members are dealt round-robin from the outer ring inward, so a small squad still reads as
 * two rings and a large one spreads evenly. */
function seatsByRing(members: readonly OrbitMember[], rings: number) {
  const byRing: OrbitMember[][] = Array.from({ length: rings }, () => []);
  members.forEach((member, index) => {
    byRing[index % rings]?.push(member);
  });
  return byRing;
}

export function OrbitSquad({
  goal,
  members,
  backedLuna,
  targetLuna,
  t = 0,
  still = false,
  totalWord = 'backed',
}: OrbitSquadProps) {
  const rings = ringCountFor(members.length);
  const byRing = seatsByRing(members, rings);
  const shown = backedLuna === null ? null : still ? backedLuna : countUp(t, backedLuna);
  const total = shown === null ? '—' : formatNim(shown);
  // The centre figure steps down a size rather than overflowing the ring on a big total.
  const size = total.length <= 6 ? 'lg' : total.length <= 9 ? 'md' : 'sm';

  return (
    <figure className="orbit" data-still={still ? 'yes' : 'no'}>
      <div className="orbit-field">
        {byRing.map((seats, ring) => {
          const diameter = RING_DIAMETERS[ring] ?? 25;
          // A still preview holds each ring at its own fixed offset, so seats on neighbouring
          // rings do not stack on the same two angles; a turning orbit separates them itself.
          const degrees = still ? ring * 45 : ringAngle(t, ringPeriod(ring), ringDirection(ring));
          return (
            <div className="orbit-ring-layer" key={`ring-${ring}`}>
              <span
                className="orbit-ring"
                aria-hidden="true"
                style={vars({
                  '--ring-size': `${diameter}%`,
                  '--ring-angle': `${degrees}deg`,
                })}
              />
              {seats.map((member, seat) => {
                const angle = seatAngle(seat, seats.length, degrees);
                const radians = (angle * Math.PI) / 180;
                const radius = diameter / 2;
                // A still preview is a finished frame, never a half-played entrance: the card
                // passes no `t`, so staggered opacity would hide every seat at t = 0.
                const enter = still ? 1 : entranceProgress(t, ring * 2 + seat);
                return (
                  <span
                    className="orbit-seat"
                    key={member.id}
                    data-tone={member.tone}
                    role="img"
                    aria-label={member.label}
                    style={vars({
                      '--seat-x': `${(50 + radius * Math.sin(radians)).toFixed(3)}%`,
                      '--seat-y': `${(50 - radius * Math.cos(radians)).toFixed(3)}%`,
                      '--enter': enter,
                    })}
                  >
                    {member.identiconSvg === null ? (
                      <span className="orbit-seat-blank" />
                    ) : (
                      // Generated by us from a Zod-validated NQ address, never user markup.
                      <span
                        className="orbit-seat-face"
                        dangerouslySetInnerHTML={{ __html: member.identiconSvg }}
                      />
                    )}
                  </span>
                );
              })}
            </div>
          );
        })}
        <div className="orbit-centre">
          <p className="orbit-total" data-size={size}>{total}</p>
          <p className="orbit-of">
            {targetLuna === null
              ? `NIM ${totalWord}`
              : `${totalWord} of ${formatNim(targetLuna)} NIM`}
          </p>
        </div>
      </div>
      <figcaption className="orbit-goal">{goal}</figcaption>
    </figure>
  );
}

export interface OrbitSceneProps extends OrbitSquadProps {
  heading: string;
}

/** The orbit on its own inside a phone frame, for the fixture gallery and the video. */
export function OrbitScene({ heading, demoLabel, ...props }: OrbitSceneProps & { demoLabel?: string | undefined }) {
  return (
    <main className="sheet">
      <ScreenHeader demoLabel={demoLabel} />
      <div className="sheet-body">
        <p className="eyebrow">ORBIT</p>
        <h1>{heading}</h1>
        <OrbitSquad {...props} />
      </div>
    </main>
  );
}
